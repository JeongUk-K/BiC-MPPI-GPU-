#!/usr/bin/env bash

COMMON_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$COMMON_DIR/.." && pwd)"
BUILD_DIR="$REPO_ROOT/build"
GPU_DIR="$BUILD_DIR/gpu"

repo_out_path() {
    local out="$1"
    if [[ "$out" = /* ]]; then
        printf '%s\n' "$out"
    else
        printf '%s/%s\n' "$REPO_ROOT" "$out"
    fi
}

build_relative_out_path() {
    local out="$1"
    if [[ "$out" = /* ]]; then
        printf '%s\n' "$out"
    else
        printf '../%s\n' "$out"
    fi
}

prepare_output_dir() {
    local out="$1"
    local overwrite="$2"
    if [[ "$overwrite" -eq 1 ]]; then
        rm -rf "$out"
    fi
    mkdir -p "$out"
}

write_run_manifest() {
    local out="$1"
    local runner="$2"
    shift 2
    local manifest="$out/run_manifest.txt"
    {
        printf 'runner=%s\n' "$runner"
        printf 'cwd=%s\n' "$REPO_ROOT"
        printf 'git_commit=%s\n' "$(git -C "$REPO_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
        printf 'created_at=%s\n' "$(date -Iseconds)"
        printf 'command='
        printf '%q ' "$runner" "$@"
        printf '\n'
    } > "$manifest"
}

reset_build_outputs() {
    mkdir -p "$BUILD_DIR"
    rm -f "$BUILD_DIR"/result*.csv \
          "$BUILD_DIR"/progress*.csv \
          "$BUILD_DIR"/path*.csv \
          "$BUILD_DIR"/trajectory*.csv \
          "$BUILD_DIR"/trajectory*.txt \
          "$BUILD_DIR"/*summary*.csv \
          "$BUILD_DIR"/*runs*.csv
    rm -rf "$BUILD_DIR/vis_data"
}

copy_build_csv_outputs() {
    local out="$1"
    local raw_dir="$out/raw_csv"
    mkdir -p "$raw_dir"
    find "$BUILD_DIR" -maxdepth 1 -type f \
        \( -name 'result*.csv' -o -name 'path*.csv' -o -name 'trajectory*.csv' \
           -o -name 'progress*.csv' -o -name '*progress*.csv' \
           -o -name '*summary*.csv' -o -name '*runs*.csv' \) \
        -exec cp -f {} "$raw_dir/" \;
    find "$BUILD_DIR" -maxdepth 1 -type f -name 'trajectory*.txt' \
        -exec cp -f {} "$raw_dir/" \;
}

copy_build_vis_data() {
    local out="$1"
    if [[ -d "$BUILD_DIR/vis_data" ]] &&
       find "$BUILD_DIR/vis_data" -mindepth 1 -maxdepth 1 -print -quit | grep -q .; then
        rm -rf "$out/vis_data"
        mkdir -p "$out/vis_data"
        cp -a "$BUILD_DIR/vis_data/." "$out/vis_data/"
    else
        cat > "$out/visualization_data_notes.md" <<'EOF'
# Visualization Data

No MPPIVisLogger `vis_data` directory was generated by this run.

Raw timing CSV files are still available under `raw_csv/`.  When a solver
supports rollout/cluster logging, this runner copies the binary logger output
to `vis_data/` so existing visualizers can generate PNG/GIF files later.
EOF
    fi
}

aggregate_timing_success_csv() {
    local root="$1"
    local out_csv="$2"
    python3 - "$root" "$out_csv" <<'PY'
import csv
import math
import sys
from pathlib import Path

root = Path(sys.argv[1])
out = Path(sys.argv[2])

SKIP_NAMES = {
    "aggregate_timing_success.csv",
    "outputs_manifest.csv",
    "waypoints.csv",
    "maps.csv",
    "paths.csv",
    "timings.csv",
    "trajectories.csv",
    "wmrobot_stitched_aggregate.csv",
}

def as_float(value):
    try:
        if value is None or value == "":
            return math.nan
        return float(value)
    except (TypeError, ValueError):
        return math.nan

def as_bool(value):
    if value is None:
        return False
    text = str(value).strip().lower()
    return text in {"1", "1.0", "true", "yes", "success"}

def mean(values):
    values = [v for v in values if math.isfinite(v)]
    return sum(values) / len(values) if values else math.nan

def fmt(value):
    if value is None:
        return ""
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return "nan" if not math.isfinite(value) else f"{value:.10g}"
    return str(value)

def get_value(row, *keys):
    lookup = {key.lower(): key for key in row.keys()}
    for key in keys:
        actual = lookup.get(key.lower())
        if actual is not None:
            return row.get(actual)
    return None

def first_float(row, *keys):
    fallback = math.nan
    for key in keys:
        raw = get_value(row, key)
        value = as_float(raw)
        if math.isfinite(value):
            return value
        if raw not in (None, ""):
            fallback = value
    return fallback

def row_variant(row, fallback):
    for key in ("variant", "Variant", "solver", "solver_label", "method", "label"):
        value = get_value(row, key)
        if value:
            return value
    return fallback

def summarize_regular_rows(rows, source, group, fallback_variant):
    fields = rows[0].keys() if rows else []
    if not any(
        key in fields
        for key in (
            "elapsed",
            "elapsed_total_s",
            "elapsed_rollout",
            "measured_wall_s",
            "success",
            "is_success",
            "is_failed",
            "iterations",
            "final_error",
            "f_err",
            "err",
        )
    ):
        return None

    # Manipulator trajectory logs are one run represented as many iteration rows.
    if "Iter" in fields and "err" in fields and "elapsed" in fields:
        final = rows[-1]
        elapsed_values = [as_float(r.get("elapsed")) for r in rows]
        return {
            "source": source,
            "group": group,
            "variant": fallback_variant,
            "num_rows": len(rows),
            "num_runs": 1,
            "num_success": 1 if as_float(final.get("err")) < 0.15 else 0,
            "success_rate": 1.0 if as_float(final.get("err")) < 0.15 else 0.0,
            "num_collision": "",
            "num_landed": "",
            "landed_rate": "",
            "avg_iter": as_float(final.get("Iter")),
            "avg_elapsed": sum(v for v in elapsed_values if math.isfinite(v)),
            "avg_rollout": "",
            "avg_clustering": "",
            "avg_connection": "",
            "avg_guide": "",
            "avg_f_err": as_float(final.get("err")),
            "avg_final_error": as_float(final.get("err")),
        }

    successes = []
    collisions = []
    landed = []
    iters = []
    elapsed = []
    rollout = []
    clustering = []
    connection = []
    guide = []
    f_err = []
    final_error = []

    for row in rows:
        if "is_success" in row:
            ok = as_bool(row.get("is_success"))
        elif "success" in row:
            ok = as_bool(row.get("success"))
        elif "is_failed" in row:
            ok = not as_bool(row.get("is_failed"))
        else:
            ok = None
        if ok is not None:
            successes.append(ok)
        if "is_collision" in row:
            collisions.append(as_bool(row.get("is_collision")))
        if "is_landed" in row:
            landed.append(as_bool(row.get("is_landed")))

        def append_first(dest, *keys):
            for key in keys:
                if key in row:
                    dest.append(as_float(row.get(key)))
                    return

        append_first(iters, "iter", "iterations")
        append_first(elapsed, "elapsed", "elapsed_total_s", "measured_wall_s",
                     "reported_solver_s", "effective_parallel_wall_s")
        append_first(rollout, "elapsed_rollout", "elapsed_rollout_s",
                     "rollout_s")
        append_first(clustering, "elapsed_clustering", "elapsed_clustering_s",
                     "clustering_s")
        append_first(connection, "elapsed_connection", "elapsed_connection_s",
                     "connection_s")
        append_first(guide, "elapsed_guide", "elapsed_guide_s", "guide_s")
        append_first(f_err, "f_err")
        append_first(final_error, "d_goal", "final_error", "final_cost")

    n = len(rows)
    n_success = sum(1 for v in successes if v)
    variant = row_variant(rows[0], fallback_variant)
    return {
        "source": source,
        "group": group,
        "variant": variant,
        "num_rows": len(rows),
        "num_runs": n,
        "num_success": n_success if successes else "",
        "success_rate": (n_success / len(successes)) if successes else "",
        "num_collision": sum(1 for v in collisions if v) if collisions else "",
        "num_landed": sum(1 for v in landed if v) if landed else "",
        "landed_rate": (sum(1 for v in landed if v) / len(landed)) if landed else "",
        "avg_iter": mean(iters),
        "avg_elapsed": mean(elapsed),
        "avg_rollout": mean(rollout),
        "avg_clustering": mean(clustering),
        "avg_connection": mean(connection),
        "avg_guide": mean(guide),
        "avg_f_err": mean(f_err),
        "avg_final_error": mean(final_error),
    }

def summarize_summary_rows(rows, source, group, fallback_variant):
    fields = rows[0].keys() if rows else []
    field_names = {key.lower() for key in fields}
    if not any(key in field_names for key in ("num_runs", "num_trials", "success_rate", "success rate", "num_success")):
        return None
    out_rows = []
    for row in rows:
        num_runs = as_float(get_value(row, "num_runs", "num_trials", "total_runs"))
        num_success = as_float(get_value(row, "num_success", "success_count"))
        success_rate = as_float(get_value(row, "success_rate", "Success Rate"))
        if not math.isfinite(success_rate) and math.isfinite(num_runs) and num_runs > 0 and math.isfinite(num_success):
            success_rate = num_success / num_runs
        out_rows.append({
            "source": source,
            "group": group,
            "variant": row_variant(row, fallback_variant),
            "num_rows": 1,
            "num_runs": int(num_runs) if math.isfinite(num_runs) else "",
            "num_success": int(num_success) if math.isfinite(num_success) else "",
            "success_rate": success_rate,
            "num_collision": "",
            "num_landed": get_value(row, "num_landed") or "",
            "landed_rate": get_value(row, "landed_rate") or "",
            "avg_iter": first_float(row, "avg_iter_success", "mean_iterations_success", "nbar_iter", "Nbar_iter"),
            "avg_elapsed": first_float(row, "avg_total_elapsed_success", "mean_elapsed_success_s", "tbar_elapsed", "Tbar_elapsed"),
            "avg_rollout": first_float(row, "avg_rollout_time_success", "mean_rollout_success_s"),
            "avg_clustering": first_float(row, "avg_clustering_time_success", "mean_clustering_success_s"),
            "avg_connection": first_float(row, "avg_connection_time_success", "mean_connection_success_s"),
            "avg_guide": first_float(row, "avg_guide_time_success", "mean_guide_success_s"),
            "avg_f_err": first_float(row, "avg_f_err_success", "dbar_goal"),
            "avg_final_error": first_float(row, "dbar_goal", "avg_f_err_success"),
        })
    return out_rows

summaries = []
for path in sorted(root.rglob("*.csv")):
    if (path.name in SKIP_NAMES or path.name.startswith("path_") or
            path.name.startswith("trajectory") or "progress" in path.name):
        continue
    # Most examples write both per-run result_foo.csv and a derived
    # result_foo_summary.csv. Prefer the per-run data when both exist so the
    # aggregate contains one row per variant instead of duplicate statistics.
    if path.name.endswith("_summary.csv"):
        run_csv = path.with_name(path.name.replace("_summary.csv", ".csv"))
        if run_csv.exists():
            continue
    try:
        with path.open(newline="") as f:
            rows = list(csv.DictReader(f))
    except Exception:
        continue
    if not rows:
        continue
    rel = path.relative_to(root).as_posix()
    group = rel.split("/", 1)[0] if "/" in rel else path.parent.name
    fallback_variant = path.stem.replace("result_", "").replace("_summary", "")
    summary_rows = summarize_summary_rows(rows, rel, group, fallback_variant)
    if summary_rows is not None:
        summaries.extend(summary_rows)
        continue
    summary = summarize_regular_rows(rows, rel, group, fallback_variant)
    if summary is not None:
        regular_groups = {}
        for row in rows:
            regular_groups.setdefault(row_variant(row, fallback_variant), []).append(row)
        if len(regular_groups) > 1:
            for variant, grouped_rows in regular_groups.items():
                grouped_summary = summarize_regular_rows(grouped_rows, rel, group, variant)
                if grouped_summary is not None:
                    summaries.append(grouped_summary)
        else:
            summaries.append(summary)

out.parent.mkdir(parents=True, exist_ok=True)
fields = [
    "source",
    "group",
    "variant",
    "num_rows",
    "num_runs",
    "num_success",
    "success_rate",
    "num_collision",
    "num_landed",
    "landed_rate",
    "avg_iter",
    "avg_elapsed",
    "avg_rollout",
    "avg_clustering",
    "avg_connection",
    "avg_guide",
    "avg_f_err",
    "avg_final_error",
]
with out.open("w", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=fields)
    writer.writeheader()
    for row in summaries:
        writer.writerow({key: fmt(row.get(key, "")) for key in fields})
PY
}

write_outputs_manifest() {
    local root="$1"
    local out_csv="$root/outputs_manifest.csv"
    python3 - "$root" "$out_csv" <<'PY'
import csv
import sys
from pathlib import Path

root = Path(sys.argv[1])
out = Path(sys.argv[2])
rows = []
for path in sorted(root.rglob("*")):
    if path.is_file():
        rel = path.relative_to(root).as_posix()
        rows.append({
            "path": rel,
            "bytes": path.stat().st_size,
            "kind": path.suffix.lstrip(".") or "file",
        })
with out.open("w", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=["path", "kind", "bytes"])
    writer.writeheader()
    writer.writerows(rows)
PY
}
